class RankingFeatureExtractor:
    """
    Extracts user, item, context, and retrieval features strictly from training data.
    """

    FEATURE_NAMES = [
        "item_cf_score",
        "popularity_score",
        "movie_avg_rating",
        "movie_rating_count",
        "user_avg_rating",
        "user_rating_count",
        "genre_affinity",
        "genre_overlap_count",
    ]

    def __init__(self, smoothing_weight: float = 10.0) -> None:
        """
        Parameters:
            smoothing_weight: Bayesian smoothing parameter C for movie average rating.
                              smoothed_avg = (sum_ratings + C * global_mean) / (count + C)
        """
        self.smoothing_weight = smoothing_weight

        # Global statistics
        self.global_mean_rating: float = 3.53
        self.total_train_ratings: int = 0

        # Item statistics
        self.item_counts_: Counter = Counter()
        self.item_rating_sums_: Counter = Counter()
        self.movie_genres_: dict[int, set[str]] = {}
        self.movie_titles_: dict[int, str] = {}

        # User statistics
        self.user_counts_: dict[int, int] = {}
        self.user_rating_sums_: dict[int, float] = {}
        self.user_favored_genres_: dict[int, Counter] = defaultdict(Counter)

    def load_movie_metadata(self, movies_path: Union[str, Path]) -> None:
        """Load movie titles and genres from movies.csv."""
        movies_path = Path(movies_path)
        if not movies_path.exists():
            return

        df = pd.read_csv(movies_path, usecols=["movieId", "title", "genres"])
        for _, row in df.iterrows():
            mid = int(row["movieId"])
            self.movie_titles_[mid] = str(row["title"])
            genre_str = str(row["genres"])
            if genre_str and genre_str != "(no genres listed)":
                self.movie_genres_[mid] = set(genre_str.split("|"))
            else:
                self.movie_genres_[mid] = set()

    def fit_from_training_stats(
        self,
        item_counts: Counter,
        item_sums: Counter,
        user_counts: dict[int, int],
        user_sums: dict[int, float],
        user_genres: Optional[dict[int, Counter]] = None,
        movie_genres: Optional[dict[int, set[str]]] = None,
    ) -> RankingFeatureExtractor:
        """Directly populate statistics (useful for synthetic testing)."""
        self.item_counts_ = item_counts
        self.item_rating_sums_ = item_sums
        self.user_counts_ = user_counts
        self.user_rating_sums_ = user_sums
        if user_genres is not None:
            self.user_favored_genres_ = defaultdict(Counter, user_genres)
        if movie_genres is not None:
            self.movie_genres_ = movie_genres

        total_sum = sum(item_sums.values())
        total_cnt = sum(item_counts.values())
        if total_cnt > 0:
            self.global_mean_rating = total_sum / total_cnt
            self.total_train_ratings = total_cnt
        return self

    def fit(
        self,
        ratings_path: Union[str, Path],
        movies_path: Optional[Union[str, Path]] = None,
        train_cutoff_timestamp: int = DEFAULT_TRAIN_CUTOFF,
        chunksize: int = 1_000_000,
    ) -> RankingFeatureExtractor:
        """
        Extract user and item statistics strictly from training ratings (timestamp <= cutoff).
        Vectorized Pandas aggregation for fast chunked streaming.
        """
        ratings_path = Path(ratings_path)
        if movies_path is not None:
            self.load_movie_metadata(movies_path)

        item_counts: Counter = Counter()
        item_sums: Counter = Counter()
        user_counts: dict[int, int] = defaultdict(int)
        user_sums: dict[int, float] = defaultdict(float)

        for chunk in pd.read_csv(
            ratings_path,
            chunksize=chunksize,
            usecols=["userId", "movieId", "rating", "timestamp"],
        ):
            train_mask = chunk["timestamp"] <= train_cutoff_timestamp
            train_chunk = chunk[train_mask]
            if train_chunk.empty:
                continue

            # Vectorized aggregation for movies
            item_stats = train_chunk.groupby("movieId")["rating"].agg(["count", "sum"])
            mids = item_stats.index.to_numpy(dtype=np.int32)
            cnts = item_stats["count"].to_numpy(dtype=np.int32)
            sums = item_stats["sum"].to_numpy(dtype=np.float32)
            for m, c, s in zip(mids, cnts, sums):
                item_counts[int(m)] += int(c)
                item_sums[int(m)] += float(s)

            # Vectorized aggregation for users
            user_stats = train_chunk.groupby("userId")["rating"].agg(["count", "sum"])
            uids = user_stats.index.to_numpy(dtype=np.int32)
            u_cnts = user_stats["count"].to_numpy(dtype=np.int32)
            u_sums = user_stats["sum"].to_numpy(dtype=np.float32)
            for u, c, s in zip(uids, u_cnts, u_sums):
                user_counts[int(u)] += int(c)
                user_sums[int(u)] += float(s)

        self.item_counts_ = item_counts
        self.item_rating_sums_ = item_sums
        self.user_counts_ = dict(user_counts)
        self.user_rating_sums_ = dict(user_sums)

        total_cnt = sum(item_counts.values())
        total_sum = sum(item_sums.values())
        if total_cnt > 0:
            self.global_mean_rating = total_sum / total_cnt
            self.total_train_ratings = total_cnt

        return self

    def get_movie_avg_rating(self, movie_id: int) -> float:
        """Bayesian smoothed movie average rating."""
        cnt = self.item_counts_.get(movie_id, 0)
        if cnt == 0:
            return self.global_mean_rating
        s = self.item_rating_sums_.get(movie_id, 0.0)
        return (s + self.smoothing_weight * self.global_mean_rating) / (cnt + self.smoothing_weight)

    def get_user_avg_rating(self, user_id: int) -> float:
        """User average rating in training set."""
        cnt = self.user_counts_.get(user_id, 0)
        if cnt == 0:
            return self.global_mean_rating
        return self.user_rating_sums_.get(user_id, 0.0) / cnt

    def extract_features_single(
        self,
        user_id: int,
        movie_id: int,
        cf_score: float = 0.0,
        popularity_count: Optional[int] = None,
        user_favored_genres: Optional[Counter] = None,
    ) -> np.ndarray:
        """
        Extract the 8 features for a single (user, movie) pair.
        """
        pop_cnt = self.item_counts_.get(movie_id, 0) if popularity_count is None else popularity_count
        pop_score = min(1.0, pop_cnt / 65000.0)
        movie_avg = self.get_movie_avg_rating(movie_id)
        log_movie_cnt = math.log10(1 + pop_cnt)

        user_cnt = self.user_counts_.get(user_id, 0)
        user_avg = self.get_user_avg_rating(user_id)
        log_user_cnt = math.log10(1 + user_cnt)

        # Genre features
        movie_g = self.movie_genres_.get(movie_id, set())
        user_g_counter = user_favored_genres if user_favored_genres is not None else self.user_favored_genres_.get(user_id, Counter())
        total_user_fav_genres = sum(user_g_counter.values())

        if movie_g and total_user_fav_genres > 0:
            overlap_count = sum(user_g_counter[g] for g in movie_g if g in user_g_counter)
            genre_affinity = overlap_count / total_user_fav_genres
            unique_overlap = len(movie_g.intersection(user_g_counter.keys()))
        else:
            genre_affinity = 0.0
            unique_overlap = 0

        return np.array([
            cf_score,
            pop_score,
            movie_avg,
            log_movie_cnt,
            user_avg,
            log_user_cnt,
            genre_affinity,
            float(unique_overlap),
        ], dtype=np.float32)

    def extract_candidate_matrix(
        self,
        user_id: int,
        candidate_ids: list[int],
        cf_scores: Optional[dict[int, float]] = None,
        user_favored_genres: Optional[Counter] = None,
    ) -> np.ndarray:
        """
        Extract feature matrix of shape (len(candidate_ids), 8).
        """
        if not candidate_ids:
            return np.empty((0, len(self.FEATURE_NAMES)), dtype=np.float32)

        cf_scores = cf_scores or {}
        rows = []
        for mid in candidate_ids:
            cf_score = cf_scores.get(mid, 0.0)
            rows.append(self.extract_features_single(
                user_id, mid, cf_score=cf_score, user_favored_genres=user_favored_genres
            ))
        return np.vstack(rows)


