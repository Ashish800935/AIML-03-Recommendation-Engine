# =============================================================================
# Precision@K Metric
# =============================================================================

def compute_precision_at_k(
    recommended: list[int],
    ground_truth: set[int],
    k: int,
) -> float:
    """
    Compute Precision@K for a single user.

    Formula:
        Precision@K = |Top-K Recommendations ∩ Ground Truth| / K

    Parameters:
        recommended: Ordered list of recommended movieIds.
        ground_truth: Set of relevant movieIds in the evaluation set.
        k: Cutoff rank (e.g. 5, 10, 20).

    Returns:
        Precision score in [0.0, 1.0]. Returns 0.0 if ground_truth is empty or k <= 0.
    """
    if not ground_truth or k <= 0:
        return 0.0

    k_recommended = recommended[:k]
    hits = len(set(k_recommended).intersection(ground_truth))
    return hits / k


