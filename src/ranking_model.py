# Pointwise Logistic Ranking Model
# =============================================================================

class RankingModel:
    """
    Pointwise regularized logistic regression ranking model for Stage 2 reranking.
    """

    def __init__(
        self,
        feature_extractor: Optional[RankingFeatureExtractor] = None,
        candidate_retriever: Optional[CandidateRetriever] = None,
        l2_reg: float = 1.0,
    ) -> None:
        """
        Parameters:
            feature_extractor: Fitted RankingFeatureExtractor.
            candidate_retriever: Fitted CandidateRetriever (Phase 5A).
            l2_reg: L2 regularization strength lambda.
        """
        self.feature_extractor = feature_extractor or RankingFeatureExtractor()
        self.candidate_retriever = candidate_retriever
        self.l2_reg = l2_reg

        # Model parameters: weights and bias
        self.weights_: np.ndarray = np.zeros(len(RankingFeatureExtractor.FEATURE_NAMES), dtype=np.float32)
        self.bias_: float = 0.0
        self.is_fitted_: bool = False

        # Feature normalization parameters (mean and std)
        self.scaler_mean_: np.ndarray = np.zeros(len(RankingFeatureExtractor.FEATURE_NAMES), dtype=np.float32)
        self.scaler_std_: np.ndarray = np.ones(len(RankingFeatureExtractor.FEATURE_NAMES), dtype=np.float32)

    def _normalize(self, X: np.ndarray) -> np.ndarray:
        return (X - self.scaler_mean_) / self.scaler_std_

    def fit_weights(self, X: np.ndarray, y: np.ndarray) -> RankingModel:
        """
        Fit logistic regression weights on feature matrix X and binary labels y.
        Uses SciPy L-BFGS-B with L2 regularization.
        """
        n_samples, n_features = X.shape
        if n_samples == 0:
            return self

        # Compute z-score scaling
        self.scaler_mean_ = np.mean(X, axis=0)
        std = np.std(X, axis=0)
        std[std == 0.0] = 1.0
        self.scaler_std_ = std

        X_norm = self._normalize(X)

        def loss_and_grad(params: np.ndarray) -> tuple[float, np.ndarray]:
            w = params[:-1]
            b = params[-1]

            logits = X_norm @ w + b
            preds = expit(logits)
            # Clip for numerical stability
            preds = np.clip(preds, 1e-7, 1.0 - 1e-7)

            # Binary cross entropy + L2 penalty
            bce = -np.mean(y * np.log(preds) + (1.0 - y) * np.log(1.0 - preds))
            reg = 0.5 * (self.l2_reg / n_samples) * np.sum(w ** 2)
            total_loss = float(bce + reg)

            # Gradient
            diff = (preds - y) / n_samples
            grad_w = (X_norm.T @ diff) + (self.l2_reg / n_samples) * w
            grad_b = np.sum(diff)
            grad = np.append(grad_w, grad_b)

            return total_loss, grad

        init_params = np.zeros(n_features + 1, dtype=np.float64)

        res = minimize(
            fun=loss_and_grad,
            x0=init_params,
            jac=True,
            method="L-BFGS-B",
            options={"maxiter": 100},
        )

        self.weights_ = res.x[:-1].astype(np.float32)
        self.bias_ = float(res.x[-1])
        self.is_fitted_ = True
        return self

    def predict_scores(self, X: np.ndarray) -> np.ndarray:
        """
        Compute Stage 2 ranking scores:
          Score = expit(base_cf_norm + X_norm @ w + b)
        Combining Stage 1 retrieval affinity with Stage 2 quality and context adjustments.
        """
        if len(X) == 0:
            return np.empty(0, dtype=np.float32)

        # Feature 0 is cf_score; normalize it within the candidate set
        raw_cf = X[:, 0]
        max_cf = np.max(raw_cf) if len(raw_cf) > 0 else 1.0
        cf_norm = raw_cf / (max_cf + 1e-6)

        if not self.is_fitted_:
            return expit(cf_norm)

        X_norm = self._normalize(X)
        adjustment = X_norm @ self.weights_ + self.bias_
        logits = cf_norm + adjustment
        return expit(logits)

    def rank_candidates(
        self,
        user_id: int,
        candidate_ids: list[int],
        user_history: Optional[Union[set[int], list[int]]] = None,
        cf_scores: Optional[dict[int, float]] = None,
        k: int = 10,
    ) -> list[int]:
        """
        Rerank a candidate shortlist for a user and return the top-K recommendations.

        Parameters:
            user_id: The target userId.
            candidate_ids: List of candidate movieIds from Phase 5A retrieval.
            user_history: Set/list of movies already rated in training (filtered out).
            cf_scores: Optional dict of {movieId: similarity_score} from Item-CF.
            k: Number of final recommendations to return (e.g. 10).

        Returns:
            List of top-K movieIds sorted descending by predicted ranking score.
        """
        if k <= 0 or not candidate_ids:
            return []

        seen_set = set(user_history) if user_history else set()
        # Ensure seen items are excluded
        valid_candidates = [mid for mid in candidate_ids if mid not in seen_set]
        if not valid_candidates:
            return []

        # If model is not yet fitted, preserve candidate generator ordering
        if not self.is_fitted_:
            return valid_candidates[:k]

        # Extract features for all candidates
        user_g_counter = Counter(
            g for mid in seen_set
            for g in self.feature_extractor.movie_genres_.get(mid, ())
        ) if seen_set else None

        X = self.feature_extractor.extract_candidate_matrix(
            user_id=user_id,
            candidate_ids=valid_candidates,
            cf_scores=cf_scores,
            user_favored_genres=user_g_counter,
        )
        scores = self.predict_scores(X)

        # Sort candidates descending by predicted score, tie-break by movieId ascending
        ranked_pairs = sorted(
            zip(valid_candidates, scores),
            key=lambda x: (-x[1], x[0]),
        )
        return [mid for mid, _ in ranked_pairs[:k]]

    def rank_with_details(
        self,
        user_id: int,
        candidate_ids: list[int],
        user_history: Optional[Union[set[int], list[int]]] = None,
        cf_scores: Optional[dict[int, float]] = None,
        k: int = 10,
    ) -> list[dict]:
        """
        Rerank candidates and return rich details including score, rank, and features.
        """
        recs = self.rank_candidates(
            user_id=user_id,
            candidate_ids=candidate_ids,
            user_history=user_history,
            cf_scores=cf_scores,
            k=k,
        )
        results = []
        for rank, mid in enumerate(recs, start=1):
            feat = self.feature_extractor.extract_features_single(user_id, mid)
            results.append({
                "rank": rank,
                "movieId": mid,
                "title": self.feature_extractor.movie_titles_.get(mid, f"Movie {mid}"),
                "genres": "|".join(sorted(self.feature_extractor.movie_genres_.get(mid, set()))) or "Unknown",
                "movie_avg_rating": round(float(feat[2]), 2),
                "popularity_count": self.feature_extractor.item_counts_.get(mid, 0),
            })
        return results


# =============================================================================
# Ranking Model Training Pipeline (From Training Data Only)
# =============================================================================

def train_ranking_model_from_history(
    model: RankingModel,
    user_train_history: dict[int, list[int]],
    retriever: CandidateRetriever,
    max_train_users: int = 3000,
    candidate_pool_size: int = 50,
    neg_ratio: int = 4,
    random_seed: int = 42,
) -> RankingModel:
    """
    Train RankingModel weights strictly on Stage 1 retrieved candidates using training interactions.

    Constructs training pairs strictly from retrieved candidates:
      - Chronological split: first 75% of user's training history as profile, last 25% as target interactions.
      - Candidates generated using profile history through Phase 5A retriever.
      - Positives (y=1): retrieved candidates appearing in target interactions.
      - Negatives (y=0): retrieved candidates NOT appearing in target interactions.
    """
    rng = random.Random(random_seed)

    eligible_users = sorted(uid for uid, hist in user_train_history.items() if len(hist) >= 6)
    if not eligible_users:
        return model

    if 0 < max_train_users < len(eligible_users):
        sample_users = sorted(rng.sample(eligible_users, max_train_users))
    else:
        sample_users = eligible_users

    X_list: list[np.ndarray] = []
    y_list: list[int] = []

    for uid in sample_users:
        full_hist = user_train_history[uid]
        if len(full_hist) < 4:
            continue

        # Chronological 75/25 split of user history
        split_idx = max(2, int(len(full_hist) * 0.75))
        profile_hist = full_hist[:split_idx]
        target_positives = set(full_hist[split_idx:])

        if not target_positives:
            continue

        # Generate candidates strictly from profile history
        cands = retriever.retrieve_candidates(user_history=profile_hist, k=candidate_pool_size)
        raw_cf = dict(retriever._get_raw_item_cf_candidates(set(profile_hist), limit=candidate_pool_size))

        # Profile-history-only favored genres (zero leakage of target preferences)
        user_g_counter = Counter(
            g for mid in profile_hist
            for g in model.feature_extractor.movie_genres_.get(mid, ())
        )

        pos_in_cands = [m for m in cands if m in target_positives]
        neg_in_cands = [m for m in cands if m not in target_positives]

        # Only users with at least 1 hit in the candidate pool provide discriminative signal
        if not pos_in_cands:
            continue

        for mid in pos_in_cands:
            cf_s = raw_cf.get(mid, 0.0)
            feat = model.feature_extractor.extract_features_single(
                uid, mid, cf_score=cf_s, user_favored_genres=user_g_counter
            )
            X_list.append(feat)
            y_list.append(1)

        for mid in neg_in_cands[:len(pos_in_cands) * neg_ratio]:
            cf_s = raw_cf.get(mid, 0.0)
            feat = model.feature_extractor.extract_features_single(
                uid, mid, cf_score=cf_s, user_favored_genres=user_g_counter
            )
            X_list.append(feat)
            y_list.append(0)

    if not X_list:
        return model

    X = np.vstack(X_list)
    y = np.array(y_list, dtype=np.float32)

    model.fit_weights(X, y)
    return model


